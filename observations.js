"use strict";
(() => {
  const get = id => document.getElementById(id);
  let rows = [], index = 0, timer = null;
  const models = ["train_mean", "behavior", "eeg_summary", "eeg_channels"];
  function pause() {
    clearInterval(timer);
    timer = null;
    get("observed-play").textContent = "Play";
  }
  function draw() {
    const visible = rows.slice(0, index + 1);
    const x = i => 36 + i * 540 / Math.max(1, rows.length - 1);
    const y = value => 190 - (value - 1) * 40;
    const path = key => visible.map((row, i) =>
      (i ? "L" : "M") + x(i) + " " + y(key === "observed" ? row.observed : row.predictions[key])
    ).join(" ");
    get("observed-line").setAttribute("d", path("observed"));
    get("behavior-line").setAttribute("d", path("behavior"));
    get("prediction-line").setAttribute("d", path(get("observed-model").value));
    const row = rows[index];
    get("observed-slider").value = index;
    get("observed-status").textContent =
      `Participant ${row.participant} · Video order ${row.video_order} · ${index + 1} / ${rows.length} held-out clips. Self-report ${row.observed.toFixed(2)}, behavior ${row.predictions.behavior.toFixed(2)}, selected model ${row.predictions[get("observed-model").value].toFixed(2)}.`;
  }
  get("observed-file").addEventListener("change", async event => {
    pause();
    rows = [];
    for (const id of ["observed-line", "behavior-line", "prediction-line"]) get(id).setAttribute("d", "");
    for (const id of ["observed-play", "observed-slider", "observed-model"]) get(id).disabled = true;
    try {
      const file = event.target.files[0];
      if (!file || file.size > 1000000) throw new Error("Choose a replay JSON smaller than 1 MB.");
      const data = JSON.parse(await file.text());
      if (data.schema !== "neuro-flow-replay-v1" || !Array.isArray(data.rows) || data.rows.length < 2) {
        throw new Error("Expected a replay.json generated by evaluate.py.");
      }
      const inRange = n => Number.isFinite(n) && n >= 1 && n <= 5;
      if (!data.rows.every((row, i) =>
        Number.isInteger(row.participant) && Number.isInteger(row.video_order) &&
        inRange(row.observed) && row.predictions &&
        models.every(key => inRange(row.predictions[key])) &&
        (!i || (row.participant === data.rows[0].participant && row.video_order > data.rows[i - 1].video_order))
      )) throw new Error("Replay must contain one participant, ordered clips and finite scores from 1 to 5.");
      rows = data.rows;
      index = 0;
      get("observed-slider").max = rows.length - 1;
      for (const id of ["observed-play", "observed-slider", "observed-model"]) get(id).disabled = false;
      draw();
    } catch (error) {
      get("observed-status").textContent = error.message;
    }
  });
  get("observed-play").addEventListener("click", () => {
    if (timer !== null) { pause(); return; }
    if (index === rows.length - 1) index = 0;
    get("observed-play").textContent = "Pause";
    draw();
    timer = setInterval(() => {
      if (document.hidden) return;
      index += 1;
      draw();
      if (index === rows.length - 1) pause();
    }, 850);
  });
  get("observed-slider").addEventListener("input", event => {
    pause(); index = Number(event.target.value); draw();
  });
  get("observed-model").addEventListener("change", () => { if (rows.length) draw(); });
})();
